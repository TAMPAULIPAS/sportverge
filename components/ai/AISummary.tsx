// ─────────────────────────────────────────────────────────────
//  🎬 STREAMING TEXT HOOK
// ─────────────────────────────────────────────────────────────

function useStreamingText(text: string, enabled: boolean) {
  const [displayed, setDisplayed] = useState(enabled ? "" : text);
  const [isDone, setIsDone] = useState(!enabled);

  useEffect(() => {
    if (!enabled) {
      setDisplayed(text);
      setIsDone(true);
      return;
    }

    setDisplayed("");
    setIsDone(false);

    const chars = Array.from(text);
    const speedMs = Math.max(8, Math.min(25, 1500 / chars.length));
    let idx = 0;
    let cancelled = false;

    const timer = setInterval(() => {
      if (cancelled) return;
      idx += 1;
      setDisplayed(chars.slice(0, idx).join(""));
      if (idx >= chars.length) {
        clearInterval(timer);
        setIsDone(true);
      }
    }, speedMs);

    return () => {
      cancelled = true;
      clearInterval(timer);
    };
  }, [text, enabled]);

  return { displayed, isDone };
}

